/// Balanced chord-corpus manifest contract and validators (E14-R25,
/// ADR 0538).
///
/// SDD Ch14 §7.1 asks for a corpus this repository does not have: 8 players,
/// 6 phone models, 4 guitars, pick and finger, quiet/medium/loud, ≥4 rooms
/// and several distances, 24 balanced maj/min classes, hard negatives, and a
/// player/device/guitar grouped holdout. This file cannot conjure that data.
/// What it CAN do — and does — is make the corpus's shape machine-checkable
/// BEFORE anyone records it, so the recording session cannot quietly end up
/// unbalanced or leaky:
///
/// * every item must name its `voicing`, `capo`, `pickStyle`, `loudness`,
///   `room`, `distanceCm`, `guitar`, `player` and `device` — no optional
///   metadata, because a field that may be missing is a field that will be
///   missing exactly where the analysis needs it;
/// * [ChordCorpusManifest.classBalance] reports per-class support and names
///   the classes below a required minimum;
/// * the grouped-split disjointness check REUSES the shipped
///   `recognition_split.dart` builder + leakage detector — one implementation
///   of "a player never crosses the train/eval boundary", not two;
/// * a SYNTHETIC corpus is a first-class, explicitly labelled kind, and
///   [ChordCorpusManifest.gateEvidenceRefusal] refuses it as release
///   evidence (SDD Ch14 §12/2: synthetic audio validates the VALIDATOR, it
///   is never ground truth).
///
/// This file never opens a file or a socket.
library;

import 'dart:convert';

import 'recognition_metrics.dart' show RecognitionCase;
import 'recognition_split.dart';

/// The 24 supported chord classes (12 major + 12 minor), in the index order
/// of `assets/ml/model_manifest.json`'s `output_classes` minus its leading
/// `N.C.` entry. A test mirrors this list against the shipped manifest, so a
/// vocabulary change cannot land on one side only.
const List<String> chordCorpusMajMin24Labels = <String>[
  'C',
  'C#',
  'D',
  'D#',
  'E',
  'F',
  'F#',
  'G',
  'G#',
  'A',
  'A#',
  'B',
  'Cm',
  'C#m',
  'Dm',
  'D#m',
  'Em',
  'Fm',
  'F#m',
  'Gm',
  'G#m',
  'Am',
  'A#m',
  'Bm',
];

/// The reserved "nothing is sounding" label, matching
/// `recognition_metrics.dart`'s `chordNoChordF1` label.
const String chordCorpusNoChordLabel = 'noChord';

/// Where the audio came from.
enum ChordCorpusKind {
  /// Recorded from a real guitar and a real microphone.
  realAudio,

  /// Generated by a synthesiser. Usable to exercise a validator or a
  /// decoder's plumbing, NEVER as release evidence.
  synthetic;

  static ChordCorpusKind fromJson(Object? value, String path) =>
      switch (value) {
        'realAudio' => ChordCorpusKind.realAudio,
        'synthetic' => ChordCorpusKind.synthetic,
        _ => throw ChordCorpusConfigException(
          ChordCorpusConfigErrorKind.malformedValue,
          'unknown corpus kind "$value" (expected realAudio/synthetic)',
          path: path,
        ),
      };

  String toJson() => name;
}

enum ChordVoicing {
  open,
  barre,
  alt;

  static ChordVoicing fromJson(Object? value, String path) => switch (value) {
    'open' => ChordVoicing.open,
    'barre' => ChordVoicing.barre,
    'alt' => ChordVoicing.alt,
    _ => throw ChordCorpusConfigException(
      ChordCorpusConfigErrorKind.malformedValue,
      'unknown voicing "$value" (expected "open", "barre" or "alt")',
      path: path,
    ),
  };

  String toJson() => name;
}

enum ChordPickStyle {
  pick,
  finger;

  static ChordPickStyle fromJson(Object? value, String path) =>
      switch (value) {
        'pick' => ChordPickStyle.pick,
        'finger' => ChordPickStyle.finger,
        _ => throw ChordCorpusConfigException(
          ChordCorpusConfigErrorKind.malformedValue,
          'unknown pick style "$value" (expected "pick" or "finger")',
          path: path,
        ),
      };

  String toJson() => name;
}

enum ChordLoudness {
  quiet,
  medium,
  loud;

  static ChordLoudness fromJson(Object? value, String path) =>
      switch (value) {
        'quiet' => ChordLoudness.quiet,
        'medium' => ChordLoudness.medium,
        'loud' => ChordLoudness.loud,
        _ => throw ChordCorpusConfigException(
          ChordCorpusConfigErrorKind.malformedValue,
          'unknown loudness "$value" (expected quiet/medium/loud)',
          path: path,
        ),
      };

  String toJson() => name;
}

enum ChordCorpusConfigErrorKind {
  malformedValue,
  missingField,
  unknownField,
  unknownSchemaVersion,
  duplicateItemId,
  unknownLabel,
}

/// A typed manifest failure — never a bare [FormatException].
final class ChordCorpusConfigException implements Exception {
  const ChordCorpusConfigException(this.kind, this.message, {this.path});

  final ChordCorpusConfigErrorKind kind;
  final String message;
  final String? path;

  @override
  String toString() =>
      'ChordCorpusConfigException(${kind.name})'
      '${path == null ? '' : ' at $path'}: $message';
}

/// The only manifest schema version this contract accepts.
const String supportedChordCorpusSchemaVersion = '1';

/// One recorded (or generated) item.
final class ChordCorpusItem {
  const ChordCorpusItem({
    required this.itemId,
    required this.label,
    required this.voicing,
    required this.capo,
    required this.pickStyle,
    required this.loudness,
    required this.room,
    required this.distanceCm,
    required this.guitar,
    required this.player,
    required this.device,
    required this.durationMs,
    required this.tempoBpm,
    required this.hardNegativeCategory,
  });

  final String itemId;

  /// A member of [chordCorpusMajMin24Labels], or
  /// [chordCorpusNoChordLabel] for a silence/hard-negative item.
  final String label;

  final ChordVoicing voicing;

  /// Fret the capo sits on; `0` for no capo.
  final int capo;

  final ChordPickStyle pickStyle;
  final ChordLoudness loudness;
  final String room;
  final int distanceCm;
  final String guitar;
  final String player;
  final String device;
  final int durationMs;
  final int tempoBpm;

  /// The `negative_taxonomy.json` category id when this item is a hard
  /// negative, otherwise `null`. A hard negative always carries
  /// [chordCorpusNoChordLabel].
  final String? hardNegativeCategory;

  bool get isHardNegative => hardNegativeCategory != null;

  Map<String, Object?> toJson() => <String, Object?>{
    'itemId': itemId,
    'label': label,
    'voicing': voicing.toJson(),
    'capo': capo,
    'pickStyle': pickStyle.toJson(),
    'loudness': loudness.toJson(),
    'room': room,
    'distanceCm': distanceCm,
    'guitar': guitar,
    'player': player,
    'device': device,
    'durationMs': durationMs,
    'tempoBpm': tempoBpm,
    'hardNegativeCategory': hardNegativeCategory,
  };
}

/// Per-class support, and what is missing.
final class ChordClassBalanceReport {
  const ChordClassBalanceReport({
    required this.supportByLabel,
    required this.missingLabels,
    required this.minimumSupport,
    required this.labelsBelowMinimum,
    required this.noChordItemCount,
    required this.hardNegativeItemCount,
    required this.totalItemCount,
  });

  /// Item count per supported label, every label of
  /// [chordCorpusMajMin24Labels] present as a key (`0` when unrecorded).
  final Map<String, int> supportByLabel;

  /// Labels with zero items, sorted.
  final List<String> missingLabels;

  final int minimumSupport;

  /// Labels below [minimumSupport] (including the missing ones), sorted.
  final List<String> labelsBelowMinimum;

  final int noChordItemCount;
  final int hardNegativeItemCount;
  final int totalItemCount;

  /// `true` only when every supported class reaches [minimumSupport].
  bool get meetsMinimumSupport => labelsBelowMinimum.isEmpty;

  /// Hard negatives as a share of all items — `null` when the corpus is
  /// empty (never `0`, which would read as "measured, and there are none").
  double? get hardNegativeShare =>
      totalItemCount == 0 ? null : hardNegativeItemCount / totalItemCount;

  Map<String, Object?> toJson() => <String, Object?>{
    'supportByLabel': supportByLabel,
    'missingLabels': missingLabels,
    'minimumSupport': minimumSupport,
    'labelsBelowMinimum': labelsBelowMinimum,
    'noChordItemCount': noChordItemCount,
    'hardNegativeItemCount': hardNegativeItemCount,
    'totalItemCount': totalItemCount,
    'meetsMinimumSupport': meetsMinimumSupport,
    'hardNegativeShare': hardNegativeShare,
  };
}

/// A parsed corpus manifest.
final class ChordCorpusManifest {
  const ChordCorpusManifest({
    required this.schemaVersion,
    required this.corpusId,
    required this.corpusKind,
    required this.corpusSha256,
    required this.items,
  });

  final String schemaVersion;
  final String corpusId;
  final ChordCorpusKind corpusKind;

  /// Content hash of the audio the manifest describes. Never the audio
  /// itself — no raw recording is ever committed (ADR 0354 D1).
  final String corpusSha256;

  final List<ChordCorpusItem> items;

  /// Why this corpus may not be used as release-gate evidence, or `null`
  /// when it may. Synthetic audio is refused unconditionally (SDD Ch14
  /// §12/2) — the refusal is a value, not a thrown error, so a caller can
  /// still legitimately use a synthetic corpus to exercise plumbing.
  String? get gateEvidenceRefusal {
    switch (corpusKind) {
      case ChordCorpusKind.realAudio:
        return null;
      case ChordCorpusKind.synthetic:
        return 'corpus "$corpusId" is SYNTHETIC: generated audio exercises '
            'the validator and the decoder plumbing, it is never ground '
            'truth for a release gate (SDD Ch14 §12/2)';
    }
  }

  /// Per-class support against [chordCorpusMajMin24Labels].
  ChordClassBalanceReport classBalance({required int minimumSupport}) {
    if (minimumSupport < 0) {
      throw ArgumentError.value(
        minimumSupport,
        'minimumSupport',
        'must not be negative',
      );
    }
    final support = <String, int>{
      for (final label in chordCorpusMajMin24Labels) label: 0,
    };
    var noChord = 0;
    var hardNegatives = 0;
    for (final item in items) {
      if (item.isHardNegative) hardNegatives++;
      if (item.label == chordCorpusNoChordLabel) {
        noChord++;
        continue;
      }
      support[item.label] = (support[item.label] ?? 0) + 1;
    }
    final missing = <String>[];
    final below = <String>[];
    for (final entry in support.entries) {
      if (entry.value == 0) missing.add(entry.key);
      if (entry.value < minimumSupport) below.add(entry.key);
    }
    missing.sort();
    below.sort();
    return ChordClassBalanceReport(
      supportByLabel: Map<String, int>.unmodifiable(support),
      missingLabels: List<String>.unmodifiable(missing),
      minimumSupport: minimumSupport,
      labelsBelowMinimum: List<String>.unmodifiable(below),
      noChordItemCount: noChord,
      hardNegativeItemCount: hardNegatives,
      totalItemCount: items.length,
    );
  }

  /// The corpus as [RecognitionCase]s carrying only the four group keys, so
  /// the SHIPPED split builder and leakage detector can be run over it
  /// unchanged. The cases carry no events: this projection exists for
  /// splitting, not for scoring.
  List<RecognitionCase> toSplitCases() => <RecognitionCase>[
    for (final item in items)
      RecognitionCase(
        caseId: item.itemId,
        player: item.player,
        device: item.device,
        guitar: item.guitar,
        room: item.room,
        durationMs: item.durationMs,
      ),
  ];

  /// Builds every fold of [strategy] and validates it for leakage, using
  /// `recognition_split.dart`. Throws [RecognitionSplitException] on a
  /// missing group key or a leak — the same typed failures the recognition
  /// evaluation already raises.
  List<RecognitionSplitFold> buildFolds(SplitStrategy strategy) =>
      const RecognitionSplitBuilder().buildFolds(toSplitCases(), strategy);

  Map<String, Object?> toJson() => <String, Object?>{
    'schemaVersion': schemaVersion,
    'corpusId': corpusId,
    'corpusKind': corpusKind.toJson(),
    'corpusSha256': corpusSha256,
    'items': <Map<String, Object?>>[for (final item in items) item.toJson()],
  };

  /// Deterministic JSON: the same manifest always serialises byte-identically
  /// (ADR 0354 D5 precedent).
  String toDeterministicJson() =>
      const JsonEncoder.withIndent('  ').convert(toJson());

  static ChordCorpusManifest parseJsonString(String source) {
    final Object? decoded;
    try {
      decoded = jsonDecode(source);
    } on FormatException catch (error) {
      throw ChordCorpusConfigException(
        ChordCorpusConfigErrorKind.malformedValue,
        'corpus manifest is not valid JSON: ${error.message}',
        path: 'corpus',
      );
    }
    return parse(_asMap(decoded, 'corpus'));
  }

  static ChordCorpusManifest parse(Map<String, Object?> json) {
    _checkKeys(json, _rootKeys, 'corpus');
    final schemaVersion = _requireString(json, 'schemaVersion', 'corpus');
    if (schemaVersion != supportedChordCorpusSchemaVersion) {
      throw ChordCorpusConfigException(
        ChordCorpusConfigErrorKind.unknownSchemaVersion,
        'unsupported schemaVersion "$schemaVersion" (expected '
        '"$supportedChordCorpusSchemaVersion")',
        path: 'corpus.schemaVersion',
      );
    }
    final rawItems = _asList(
      _requireField(json, 'items', 'corpus'),
      'corpus.items',
    );
    final items = <ChordCorpusItem>[];
    final seenIds = <String>{};
    for (var i = 0; i < rawItems.length; i++) {
      final path = 'corpus.items[$i]';
      final item = _parseItem(_asMap(rawItems[i], path), path);
      if (!seenIds.add(item.itemId)) {
        throw ChordCorpusConfigException(
          ChordCorpusConfigErrorKind.duplicateItemId,
          'itemId "${item.itemId}" appears twice',
          path: '$path.itemId',
        );
      }
      items.add(item);
    }
    return ChordCorpusManifest(
      schemaVersion: schemaVersion,
      corpusId: _requireNonEmptyString(json, 'corpusId', 'corpus'),
      corpusKind: ChordCorpusKind.fromJson(
        _requireField(json, 'corpusKind', 'corpus'),
        'corpus.corpusKind',
      ),
      corpusSha256: _requireNonEmptyString(json, 'corpusSha256', 'corpus'),
      items: List<ChordCorpusItem>.unmodifiable(items),
    );
  }

  static ChordCorpusItem _parseItem(Map<String, Object?> json, String path) {
    _checkKeys(json, _itemKeys, path);
    final label = _requireNonEmptyString(json, 'label', path);
    if (label != chordCorpusNoChordLabel &&
        !chordCorpusMajMin24Labels.contains(label)) {
      throw ChordCorpusConfigException(
        ChordCorpusConfigErrorKind.unknownLabel,
        'label "$label" is not a supported chord class and not '
        '"$chordCorpusNoChordLabel" — an out-of-vocabulary chord belongs in '
        'the open-set corpus, not in a balanced maj/min corpus',
        path: '$path.label',
      );
    }
    final hardNegative = json['hardNegativeCategory'] == null
        ? null
        : _requireNonEmptyString(json, 'hardNegativeCategory', path);
    if (hardNegative != null && label != chordCorpusNoChordLabel) {
      throw ChordCorpusConfigException(
        ChordCorpusConfigErrorKind.malformedValue,
        'a hard-negative item must carry the "$chordCorpusNoChordLabel" '
        'label, not "$label"',
        path: '$path.hardNegativeCategory',
      );
    }
    return ChordCorpusItem(
      itemId: _requireNonEmptyString(json, 'itemId', path),
      label: label,
      voicing: ChordVoicing.fromJson(
        _requireField(json, 'voicing', path),
        '$path.voicing',
      ),
      capo: _requireNonNegativeInt(json, 'capo', path),
      pickStyle: ChordPickStyle.fromJson(
        _requireField(json, 'pickStyle', path),
        '$path.pickStyle',
      ),
      loudness: ChordLoudness.fromJson(
        _requireField(json, 'loudness', path),
        '$path.loudness',
      ),
      room: _requireNonEmptyString(json, 'room', path),
      distanceCm: _requirePositiveInt(json, 'distanceCm', path),
      guitar: _requireNonEmptyString(json, 'guitar', path),
      player: _requireNonEmptyString(json, 'player', path),
      device: _requireNonEmptyString(json, 'device', path),
      durationMs: _requirePositiveInt(json, 'durationMs', path),
      tempoBpm: _requirePositiveInt(json, 'tempoBpm', path),
      hardNegativeCategory: hardNegative,
    );
  }
}

const _rootKeys = <String>{
  'schemaVersion',
  'corpusId',
  'corpusKind',
  'corpusSha256',
  'items',
};
const _itemKeys = <String>{
  'itemId',
  'label',
  'voicing',
  'capo',
  'pickStyle',
  'loudness',
  'room',
  'distanceCm',
  'guitar',
  'player',
  'device',
  'durationMs',
  'tempoBpm',
  'hardNegativeCategory',
};

// --- typed field access helpers ------------------------------------------

void _checkKeys(Map<String, Object?> json, Set<String> allowed, String path) {
  for (final key in json.keys) {
    if (!allowed.contains(key)) {
      throw ChordCorpusConfigException(
        ChordCorpusConfigErrorKind.unknownField,
        'unrecognised field "$key"',
        path: '$path.$key',
      );
    }
  }
}

Object? _requireField(Map<String, Object?> json, String key, String path) {
  if (!json.containsKey(key)) {
    throw ChordCorpusConfigException(
      ChordCorpusConfigErrorKind.missingField,
      '"$key" is required',
      path: '$path.$key',
    );
  }
  return json[key];
}

String _requireString(Map<String, Object?> json, String key, String path) {
  final value = _requireField(json, key, path);
  if (value is String) return value;
  throw ChordCorpusConfigException(
    ChordCorpusConfigErrorKind.malformedValue,
    'expected a string',
    path: '$path.$key',
  );
}

String _requireNonEmptyString(
  Map<String, Object?> json,
  String key,
  String path,
) {
  final value = _requireString(json, key, path);
  if (value.isEmpty) {
    throw ChordCorpusConfigException(
      ChordCorpusConfigErrorKind.malformedValue,
      '"$key" must not be empty',
      path: '$path.$key',
    );
  }
  return value;
}

int _requireInt(Map<String, Object?> json, String key, String path) {
  final value = _requireField(json, key, path);
  if (value is int) return value;
  throw ChordCorpusConfigException(
    ChordCorpusConfigErrorKind.malformedValue,
    'expected an integer',
    path: '$path.$key',
  );
}

int _requireNonNegativeInt(Map<String, Object?> json, String key, String path) {
  final value = _requireInt(json, key, path);
  if (value < 0) {
    throw ChordCorpusConfigException(
      ChordCorpusConfigErrorKind.malformedValue,
      '"$key" must not be negative',
      path: '$path.$key',
    );
  }
  return value;
}

int _requirePositiveInt(Map<String, Object?> json, String key, String path) {
  final value = _requireInt(json, key, path);
  if (value <= 0) {
    throw ChordCorpusConfigException(
      ChordCorpusConfigErrorKind.malformedValue,
      '"$key" must be > 0',
      path: '$path.$key',
    );
  }
  return value;
}

Map<String, Object?> _asMap(Object? value, String path) {
  if (value is Map) {
    return value.map((key, v) => MapEntry(key as String, v));
  }
  throw ChordCorpusConfigException(
    ChordCorpusConfigErrorKind.malformedValue,
    'expected an object',
    path: path,
  );
}

List<Object?> _asList(Object? value, String path) {
  if (value is List) return value;
  throw ChordCorpusConfigException(
    ChordCorpusConfigErrorKind.malformedValue,
    'expected an array',
    path: path,
  );
}
